import { openRec, load } from './rec.mjs';
const r = await openRec('notifications');
const { page } = r;
await load(page);
await r.wait(1500);
await r.mark();
await r.wait(600);
const bell = page.getByRole('button', { name: 'Notifications' });
await r.hover(bell, 1100);
await r.click(bell, { post: 1400 });
const scroller = page.locator('.scroll-isolated.scroll-slim').first();
await r.hover(scroller, 500, { dy: 0.4 });
await r.wheel(420, 24, 55); await r.wait(900);
await r.wheel(-420, 16, 45); await r.wait(600);
await r.click(page.getByRole('tab', { name: 'Resolved' }).or(page.getByRole('button', { name: 'Resolved', exact: true })).first(), { post: 1500 });
await r.click(page.getByRole('tab', { name: 'Open' }).or(page.getByRole('button', { name: 'Open', exact: true })).first(), { post: 1100 });
await r.click(page.getByRole('button', { name: /All notifications/ }), { post: 700 });
await r.click(page.getByRole('menuitemradio', { name: /Unread/ }).or(page.getByRole('menuitem', { name: /Unread/ })).or(page.getByRole('option', { name: /Unread/ })).first(), { post: 1300 });
const alert = page.getByText(/unassigned orders are delayed/).first();
await r.hover(alert, 900);
const show = alert.locator('xpath=following::button[normalize-space()="Show in Deliveries"][1]');
await r.hover(show, 500);
await r.click(null, { post: 2200 });
await r.to(700, 560, 900);
await r.wait(1500);
console.log(await r.done(800));
